// overkube itself (its page's version, its license, where it is) and the libraries it runs (the page's and its server's: their dependencies, all the way down, ours aside) and
// what they are licensed under, read from their package.json in node_modules and written to src/licenses.generated.ts
// for the settings' About. Run: npm run licenses -w addons/core (a test says when it is out of date).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
/** Where it starts: what is run (the page, its server). */
const APPS = ['apps/web', 'apps/server'];
/** Taken into ours as they are, not a dependency at run time: the kit's icons (Tabler's, generated). */
const EMBEDDED = ['@tabler/icons'];
export const OUT = join(ROOT, 'addons', 'core', 'src', 'licenses.generated.ts');

const read = (dir) => JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));

/** A package's folder as Node finds it from another's: node_modules up the tree. */
function find(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const at = join(dir, 'node_modules', name);
    if (existsSync(join(at, 'package.json'))) return at;
    if (dir === dirname(dir)) throw new Error(`${name} is not installed (needed from ${from})`);
  }
}

const urlOf = (p) => {
  const repo = typeof p.repository === 'string' ? p.repository : p.repository?.url;
  return p.homepage ?? repo?.replace(/^git\+/, '').replace(/\.git$/, '');
};

/** Every library, once a license: its name, license, where it is — no version (one updated is not a change of what is listed). */
export function collect() {
  const seen = new Map();
  const visited = new Set();
  const walk = (dir) => {
    if (visited.has(dir)) return;
    visited.add(dir);
    const p = read(dir);
    if (!p.name?.startsWith('@overkube/')) {
      const license = typeof p.license === 'string' ? p.license : (p.license?.type ?? 'UNKNOWN');
      seen.set(`${p.name} ${license}`, { name: p.name, license, ...(urlOf(p) ? { url: urlOf(p) } : {}) });
    }
    // Its peers too (what it runs with), but those it can do without.
    const peers = Object.keys(p.peerDependencies ?? {}).filter((name) => !p.peerDependenciesMeta?.[name]?.optional);
    for (const name of [...Object.keys(p.dependencies ?? {}), ...peers]) walk(find(name, dir));
  };
  for (const app of APPS) walk(join(ROOT, app));
  for (const name of EMBEDDED) walk(find(name, join(ROOT, 'packages', 'uikit')));
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.license.localeCompare(b.license));
}

/** overkube itself: its page's version, its license, where it is. */
export function own() {
  const root = read(ROOT);
  return { name: 'overkube', version: read(join(ROOT, 'apps', 'web')).version, license: root.license, url: urlOf(root) };
}

export const source = (overkube, libraries) =>
  `// Generated by scripts/licenses.mjs from the installed packages. Do not edit: run it again.\n\n/** A library overkube runs: its name, license (SPDX), where it is. */\nexport interface Library {\n  name: string;\n  license: string;\n  url?: string;\n}\n\nexport const OVERKUBE: Library & { version: string } = ${JSON.stringify(overkube, null, 2)};\n\nexport const LIBRARIES: readonly Library[] = ${JSON.stringify(libraries, null, 2)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, source(own(), collect()));
  console.log(`wrote ${OUT}`);
}
