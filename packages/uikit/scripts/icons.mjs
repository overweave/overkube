const here = dirname(fileURLToPath(import.meta.url));
export const TARGET = join(here, '../src/display/icons.generated.ts');

/** The package itself (its exports let none of its files be imported): the nearest node_modules that has it. */
function tabler() {
  for (let dir = here; ; dir = dirname(dir)) {
    if (existsSync(join(dir, 'node_modules/@tabler/icons/package.json'))) return join(dir, 'node_modules/@tabler/icons');
    if (dirname(dir) === dir) throw new Error('@tabler/icons is not installed (npm install)');
  }
}

/** The generated file's text for these icons (our name → Tabler's). */
export function generate(icons = ICONS) {
  const pkg = tabler();
  const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
  const sets = {
    outline: JSON.parse(readFileSync(join(pkg, 'tabler-nodes-outline.json'), 'utf8')),
    filled: JSON.parse(readFileSync(join(pkg, 'tabler-nodes-filled.json'), 'utf8')),
  };
  const license = readFileSync(join(pkg, 'LICENSE'), 'utf8')
    .split('\n')
    .find((l) => l.startsWith('Copyright'));
  const lines = Object.entries(icons).map(([ours, theirs]) => {
    const [name, set = 'outline'] = theirs.split(':');
    const nodes = sets[set]?.[name];
    if (!nodes) throw new Error(`Tabler has no ${set} icon "${name}" (for "${ours}")`);
    const paths = nodes.map(([tag, attrs]) => {
      if (tag !== 'path') throw new Error(`"${name}": a ${tag}, not a path`);
      return attrs.d;
    });
    return `  ${JSON.stringify(ours)}: { ${set === 'filled' ? 'filled: true, ' : ''}d: ${JSON.stringify(paths)} },`;
  });
  return `// Generated by scripts/icons.mjs from @tabler/icons ${version}. Do not edit: change the script and run it again.
// Tabler Icons — MIT License, ${license} (https://tabler.io/icons): its text in the package's NOTICE.

/** An icon: its paths on a 24×24 grid, stroked (or filled). */
export interface IconData {
  d: readonly string[];
  filled?: boolean;
}

export const TABLER: Record<string, IconData> = {
${lines.join('\n')}
};
`;
}

// Run (not imported): the file written.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TARGET, generate());
  console.log(`${Object.keys(ICONS).length} icons → ${TARGET}`);
}
