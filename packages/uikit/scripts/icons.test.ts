import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
// @ts-expect-error: a plain script, no types.
import { generate, ICONS, TARGET } from './icons.mjs';

/* The icons' generator: the file in the kit is what it writes (none edited by hand, none forgotten); it takes Tabler's paths, its filled set, and refuses a name Tabler has not. */

describe('scripts/icons.mjs', () => {
  it('wrote the file in the kit as it is now: run it again after changing its list', () => {
    expect(readFileSync(TARGET, 'utf8')).toBe(generate());
  });

  it('writes each icon of its list, by our name, with Tabler’s paths', () => {
    const text: string = generate({ search: 'search' });
    expect(text).toContain('"search": { d: ["M3 10a7 7 0 1 0 14 0a7 7 0 1 0 -14 0","M21 21l-6 -6"] },');
    expect(text).not.toContain('"plus"');
    expect(Object.keys(ICONS).length).toBeGreaterThan(20);
  });

  it('takes one of Tabler’s filled set, marked filled', () => {
    expect(generate({ 'pin-filled': 'pinned:filled' })).toMatch(/"pin-filled": \{ filled: true, d: \["M16 3a1 1/);
  });

  it('says where they come from: the package, its version, its licence', () => {
    const text: string = generate({ x: 'x' });
    expect(text).toMatch(/^\/\/ Generated by scripts\/icons\.mjs from @tabler\/icons \d+\.\d+\.\d+\./);
    expect(text).toContain('MIT License, Copyright (c)');
  });

  it('refuses a name Tabler has not, or a set it has not', () => {
    expect(() => generate({ ship: 'no-such-icon' })).toThrow('Tabler has no outline icon "no-such-icon" (for "ship")');
    expect(() => generate({ ship: 'x:bold' })).toThrow('Tabler has no bold icon "x"');
  });
});
