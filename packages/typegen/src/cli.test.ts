import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

/** The CLI as it is run, against no cluster at all: what it does with the output folder comes first. */
const CLI = new URL('./cli.ts', import.meta.url).pathname;
const run = (...args: string[]) => spawnSync(process.execPath, [CLI, ...args, '--url', 'http://127.0.0.1:9'], { encoding: 'utf8' });

describe('overkube-typegen --out', () => {
  it('refuses a file, and leaves it as it was', () => {
    const file = join(mkdtempSync(join(tmpdir(), 'uk-cli-')), 'index.ts');
    writeFileSync(file, 'mine');
    const r = run('built-in', '--out', file);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain(`${file} is not a folder`);
    expect(readFileSync(file, 'utf8')).toBe('mine');
  });

  it('refuses a folder with files it did not generate, or links, and leaves them', () => {
    const dir = mkdtempSync(join(tmpdir(), 'uk-cli-'));
    mkdirSync(join(dir, 'gen'));
    writeFileSync(join(dir, 'gen', 'kinds.ts'), '// Generated by @overkube/typegen …\n');
    writeFileSync(join(dir, 'gen', 'notes.md'), 'mine');
    expect(run('group', 'x.io', '--out', join(dir, 'gen')).stderr).toContain('has files that were not generated');
    expect(existsSync(join(dir, 'gen', 'notes.md'))).toBe(true);

    const linked = mkdtempSync(join(tmpdir(), 'uk-cli-'));
    symlinkSync(join(dir, 'gen', 'notes.md'), join(linked, 'link.ts'));
    expect(run('built-in', '--out', linked).stderr).toContain('has files that were not generated');
  });

  it('goes on to the cluster for a folder of its own, or none yet', () => {
    const r = run('built-in', '--out', join(mkdtempSync(join(tmpdir(), 'uk-cli-')), 'gen'));
    expect(r.status).toBe(1);
    expect(r.stderr).toMatch(/^error: fetch failed|ECONNREFUSED/m);
  });
});
