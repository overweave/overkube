#!/usr/bin/env node
/**
 * overkube-typegen list     --url <API proxy>
 * overkube-typegen built-in --url <API proxy> --out <folder>
 * overkube-typegen group <group>… --url <API proxy> --out <folder> [--types <package>]
 *
 * list: the groups the cluster serves beyond the built-in ones (a CRD's, an
 * aggregated API's), with their kinds.
 * built-in: the types of the built-in kinds and their kinds table, one file
 * per group-version (core/v1.ts, apps/v1.ts, …) plus kinds.ts:
 * @overkube/kube-types.
 * group: the same for an addon's groups (cert-manager.io, …), every version
 * the cluster serves; the built-in types they use are imported from
 * <package> (default @overkube/kube-types), and its KindMap is extended
 * with their kinds. A built-in type they use that <package> lacks (an
 * aggregated API built on newer Kubernetes) is written with them.
 *
 * <API proxy>: `kubectl proxy`'s http://127.0.0.1:8001, or the dashboard's
 * server. <folder> is emptied first; one with files in it that were not
 * generated is left alone.
 */
import { existsSync, readFileSync } from 'node:fs';
import { lstat, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { fetchGroups, fetchSnapshot } from './fetch.ts';
import { generate } from './generate.ts';

const USAGE = `usage: overkube-typegen list --url <API proxy>
       overkube-typegen built-in --url <API proxy> --out <folder>
       overkube-typegen group <group>… --url <API proxy> --out <folder> [--types <package>]`;

const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: { url: { type: 'string' }, out: { type: 'string' }, types: { type: 'string', default: '@overkube/kube-types' } },
});
const [command, ...groups] = positionals;

function usage(): never {
  console.error(USAGE);
  process.exit(2);
}

/**
 * What under the output folder was not generated here: files without the
 * header, and anything that is not a file or a folder (a link). Nothing when
 * there is no folder yet; an error when it is not a folder at all.
 */
async function foreign(folder: string): Promise<string[]> {
  try {
    if (!(await lstat(folder)).isDirectory()) throw new Error(`${folder} is not a folder`);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw err;
  }
  const entries = (await readdir(folder, { recursive: true, withFileTypes: true })).filter((e) => !e.isDirectory());
  const own = await Promise.all(entries.map(async (e) => e.isFile() && (await readFile(join(e.parentPath, e.name), 'utf8')).startsWith('// Generated by @overkube/typegen')));
  return entries.filter((_, i) => !own[i]).map((e) => join(e.parentPath, e.name));
}

/**
 * What the built-in package installed here (node_modules, from the current
 * folder up) has: a module's file, its source or its declarations, read for
 * its exported names. Nothing when it is not installed: it is then taken to
 * have every type.
 */
function packageTypes(name: string): ((module: string, type: string) => boolean) | undefined {
  let dir = resolve('.');
  while (!existsSync(join(dir, 'node_modules', name, 'package.json'))) {
    if (dirname(dir) === dir) {
      console.error(`warning: ${name} is not installed here: taken to have every built-in type`);
      return undefined;
    }
    dir = dirname(dir);
  }
  const root = join(dir, 'node_modules', name);
  const exported = new Map<string, Set<string>>();
  return (module, type) => {
    if (!exported.has(module)) {
      const file = [join(root, 'src/gen', `${module}.ts`), join(root, 'dist/gen', `${module}.d.ts`)].find(existsSync);
      const text = file ? readFileSync(file, 'utf8') : '';
      exported.set(module, new Set([...text.matchAll(/^export (?:declare )?(?:interface|type) (\w+)/gm)].map((m) => m[1])));
    }
    return exported.get(module)?.has(type) ?? false;
  };
}

try {
  if (!values.url) usage();
  if (command === 'list' && !groups.length) {
    const added = await fetchGroups(values.url);
    if (!added.length) console.log('The cluster serves the built-in groups only.');
    for (const g of added) console.log(`${g.name}  ${g.source}  ${g.versions.join(', ')}  ${g.kinds.join(', ')}`);
  } else if ((command === 'built-in' && !groups.length) || (command === 'group' && groups.length)) {
    if (!values.out) usage();
    // Checked before anything else: nothing is asked of the cluster for a folder that will not be written.
    const left = await foreign(values.out);
    if (left.length)
      throw new Error(`${values.out} has files that were not generated (${left.slice(0, 3).join(', ')}${left.length > 3 ? ', …' : ''}); give it a folder of its own`);
    const snapshot = await fetchSnapshot(values.url, command === 'built-in' ? 'built-in' : groups);
    const { files, warnings } = generate(snapshot, command === 'group' ? { builtin: values.types, has: packageTypes(values.types) } : {});
    await rm(values.out, { recursive: true, force: true });
    for (const file of files) {
      const path = join(values.out, file.path);
      await mkdir(dirname(path), { recursive: true });
      await writeFile(path, file.text);
    }
    for (const w of warnings) console.error(`warning: ${w}`);
    console.log(`${files.length} files from Kubernetes ${snapshot.kubernetes} (${snapshot.groupVersions.length} group-versions) into ${values.out}`);
  } else {
    usage();
  }
} catch (err) {
  console.error(`error: ${(err as Error).message}`);
  process.exit(1);
}
